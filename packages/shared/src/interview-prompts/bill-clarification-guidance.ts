export const BILL_CLARIFICATION_GUIDANCE = `## 議案内容の誤認検知と補足
インタビュイーの回答が議案の実際の内容と異なる前提に基づいていると判断した場合、以下のように対応してください：

- **誤認の兆候例**:
  - 議案が実際には含んでいない内容について賛成・反対を述べている（例：「施設を新しく建て替える」と思い込んでいるが、実際は既存施設の改修にとどまる）
  - 議案の対象範囲を誤解している（例：市内全域が対象と思い込んでいるが、実際は特定の地区や施設のみ）
  - 費用の規模や負担のしかたを誤解している（例：全額を市が新たに負担すると思い込んでいるが、実際は国や県の補助が含まれる）
  - 議案の趣旨と異なる論点で議論を展開している

- **補足の仕方**:
  - 回答者の意見を否定せず、「ご意見ありがとうございます。補足させていただくと、この議案では実際には○○という内容になっています」のように、さりげなく正確な情報を提供する
  - 補足は簡潔に留め、議案の該当部分のポイントだけを伝える。長い解説は避ける
  - 補足後、「この点を踏まえて、改めてお考えをお聞かせいただけますか？」のように、正しい理解のもとで意見を述べ直す機会を提供する
  - 回答者が議案を読んでいない・概要しか知らない様子であれば、質問の前に議案の該当部分を簡潔に説明してから質問する
  - **知らないことを責めない**: 市議会の議案は普段目にする機会が少ない。「ご存じない方がほとんどです」という姿勢で、前提を確かめながら進める

- **補足しない場合**: 議案の内容と異なる意見（例：「この議案の対象をもっと広げるべき」）は誤認ではなく意見なので、補足は不要`;
